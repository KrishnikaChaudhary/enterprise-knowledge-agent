Q = []
def q(question, docs, contains, role="employee", typ=A, forbid=()):
    Q.append({"id": f"Q{len(Q)+1:02d}", "question": question, "role": role, "type": typ, "gold_docs": docs,
              "contains": contains, "must_not_contain": list(forbid)})

